"""Generates the enumeration in bb2.bend and its elimination lemmas in bb2_elim.bend.

All 6,561 two-state machines are checked by one function, all_a0(). Each of
the four rules a0, a1, b0, b1 ranges over the nine Rule2 values through four
levels of two-way conjunctions: Stop2 or Go2, then the written bit, the
direction and the next state. An elimination lemma walks the same levels back
down, so all_a0(u) == True yields check2(u, a0, a1, b0, b1) == True for any four
rules.

    python3 gen_bb2.py
"""
from pathlib import Path

HERE = Path(__file__).parent
R2 = "TM.Rule2"
LEVELS = [  # name, prefix variables, leaf call (prefix + rule)
    ("b1", ["a0", "a1", "b0"], lambda p, r: f"check2({', '.join(['u'] + p + [r])})"),
    ("b0", ["a0", "a1"], lambda p, r: f"all_b1({', '.join(['u'] + p + [r])})"),
    ("a1", ["a0"], lambda p, r: f"all_b0({', '.join(['u'] + p + [r])})"),
    ("a0", [], lambda p, r: f"all_a1({', '.join(['u'] + p + [r])})"),
]


def params(prefix, extra=()):
    return ", ".join(["+u: Nat"] + [f"+{v}: {R2}" for v in prefix] + list(extra))


def args(prefix, extra=()):
    return ", ".join(["u"] + list(prefix) + list(extra))


def go(w, d, n):
    return f"TM.Go2{{{w}, {d}, {n}}}"


def enumeration():
    out = []
    for name, p, leaf in LEVELS:
        f = f"all_{name}"
        out.append(f"""def {f}.n({params(p, ["+w: Bool", "+d: TM.Dir"])}) -> Bool:
  Bool.and({leaf(p, go("w", "d", "False{}"))}, {leaf(p, go("w", "d", "True{}"))})

def {f}.d({params(p, ["+w: Bool"])}) -> Bool:
  Bool.and({f}.n({args(p, ["w", "TM.L{}"])}), {f}.n({args(p, ["w", "TM.R{}"])}))

def {f}.w({params(p)}) -> Bool:
  Bool.and({f}.d({args(p, ["False{}"])}), {f}.d({args(p, ["True{}"])}))

def {f}({params(p)}) -> Bool:
  Bool.and({leaf(p, "TM.Stop2{}")}, {f}.w({args(p)}))
""")
    return "\n".join(out)


def elimination():
    out = []
    for name, p, leaf in LEVELS:
        f = f"B.all_{name}"
        e = f"elim_{name}"
        B = lambda s: s.replace("check2(", "B.check2(").replace("all_", "B.all_")
        lf = lambda r: B(leaf(p, r))
        gof, got = go("w", "d", "False{}"), go("w", "d", "True{}")
        out.append(f"""def {e}.n({params(p, ["+w: Bool", "+d: TM.Dir", "n: Bool"])},
    h: {{{f}.n({args(p, ["w", "d"])}) == True{{}} : Bool}}) -> {{{lf(go("w", "d", "n"))} == True{{}} : Bool}}:
  match n:
    case False{{}}:
      Lg.and_l({lf(gof)}, {lf(got)}, h)
    case True{{}}:
      Lg.and_r({lf(gof)}, {lf(got)}, h)

def {e}.d({params(p, ["+w: Bool", "d: TM.Dir", "+n: Bool"])},
    h: {{{f}.d({args(p, ["w"])}) == True{{}} : Bool}}) -> {{{lf(go("w", "d", "n"))} == True{{}} : Bool}}:
  match d:
    case TM.L{{}}:
      {e}.n({args(p, ["w", "TM.L{}", "n"])}, Lg.and_l({f}.n({args(p, ["w", "TM.L{}"])}), {f}.n({args(p, ["w", "TM.R{}"])}), h))
    case TM.R{{}}:
      {e}.n({args(p, ["w", "TM.R{}", "n"])}, Lg.and_r({f}.n({args(p, ["w", "TM.L{}"])}), {f}.n({args(p, ["w", "TM.R{}"])}), h))

def {e}.w({params(p, ["w: Bool", "+d: TM.Dir", "+n: Bool"])},
    h: {{{f}.w({args(p)}) == True{{}} : Bool}}) -> {{{lf(go("w", "d", "n"))} == True{{}} : Bool}}:
  match w:
    case False{{}}:
      {e}.d({args(p, ["False{}", "d", "n"])}, Lg.and_l({f}.d({args(p, ["False{}"])}), {f}.d({args(p, ["True{}"])}), h))
    case True{{}}:
      {e}.d({args(p, ["True{}", "d", "n"])}, Lg.and_r({f}.d({args(p, ["False{}"])}), {f}.d({args(p, ["True{}"])}), h))

def {e}({params(p, [f"r: {R2}"])}, h: {{{f}({args(p)}) == True{{}} : Bool}}) -> {{{lf("r")} == True{{}} : Bool}}:
  match r:
    case TM.Stop2{{}}:
      Lg.and_l({lf("TM.Stop2{}")}, {f}.w({args(p)}), h)
    case TM.Go2{{w, d, n}}:
      {e}.w({args(p, ["w", "d", "n"])}, Lg.and_r({lf("TM.Stop2{}")}, {f}.w({args(p)}), h))
""")
    return "\n".join(out)


BB2_HEAD = '''# BB(2): every two-state machine either halts by step 6 or is proven by the
# decider never to halt. all_a0(1n) checks all 9^4 = 6,561 of them.
# The enumeration below is generated by gen_bb2.py.
import Base
import ./tm.bend as TM
import ./abs.bend as A

# halts by step 6, or decided with one exact cell per side and 100 search steps.
# The gate u keeps every check unevaluated until u is a number: the proven
# kernel would otherwise evaluate the closed checks inside the elimination
# lemmas' types and run out of fuel. all_a0(1n) runs them all once.
def check2(u: Nat, a0: TM.Rule2, a1: TM.Rule2, b0: TM.Rule2, b1: TM.Rule2) -> Bool:
  match u:
    case 0n:
      False{}
    case 1n+v:
      A.check(TM.machine2(a0, a1, b0, b1), 6n, 1n, 100n)

'''

ELIM_HEAD = '''# Generated by gen_bb2.py: from all_a0(u) == True to check2(u, a0, a1, b0, b1) == True
# for any four rules, by walking the enumeration's conjunctions back down.
import Base
import ./tm.bend as TM
import ./logic.bend as Lg
import ./bb2.bend as B

'''

if __name__ == "__main__":
    (HERE / "bb2.bend").write_text(BB2_HEAD + enumeration())
    (HERE / "bb2_elim.bend").write_text(ELIM_HEAD + elimination())
    print("wrote bb2.bend and bb2_elim.bend")
